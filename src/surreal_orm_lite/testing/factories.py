class Faker:
    """Lightweight fake data field descriptor (the full ORM's ``Faker``).

    Supported providers:
        - ``name`` — random full name (e.g. ``"Alice Smith"``)
        - ``first_name`` — random first name
        - ``last_name`` — random last name
        - ``email`` — random email address (``"<first>.<last><3 digits>@<domain>"``)
        - ``random_int`` — random integer (kwargs: ``min`` = 0, ``max`` = 100)
        - ``random_float`` — random float rounded to 4 decimals (kwargs: ``min`` = 0.0, ``max`` = 1.0)
        - ``text`` — random words cut to ``max_length`` characters (kwargs: ``max_length`` = 200)
        - ``sentence`` — 5 to 12 words, capitalized, ending with ``.``
        - ``word`` — random single word
        - ``uuid`` — random UUID4 **string** (drawn from ``random``, so seedable)
        - ``boolean`` — random bool
        - ``date`` — random date within the last year
        - ``datetime`` — random aware UTC datetime within the last year
        - ``choice`` — random item of ``items`` (kwargs: ``items``, required and non-empty)

    Raises:
        TypeError: ``provider`` is not a string, or a keyword the provider does not take is given.
        ValueError: the provider is unknown, or ``choice`` has no (or empty) ``items``.
    """

    provider: str
    kwargs: dict[str, Any]

    def __init__(self, provider: str, **kwargs: Any) -> None:
        if not isinstance(provider, str):
            raise TypeError(f"Faker() provider must be a str, got {type(provider).__name__}")
        accepted = _PROVIDER_KWARGS.get(provider)
        if accepted is None:
            raise ValueError(f"Unknown Faker provider: {provider!r}")
        for key in kwargs:
            if key not in accepted:
                allowed = ", ".join(sorted(accepted)) if accepted else "none"
                raise TypeError(f"Faker({provider!r}) takes no keyword {key!r} (accepted: {allowed})")
        if provider == "choice":
            items = kwargs.get("items")
            if not items:
                raise ValueError("Faker('choice') requires 'items' kwarg")
            kwargs["items"] = list(items)
        self.provider = provider
        self.kwargs = kwargs

    def generate(self) -> Any:
        """Generate a random value using the configured provider."""
        method: Callable[[], Any] = getattr(self, f"_gen_{self.provider}")
        return method()

    def _gen_name(self) -> str:
        return f"{random.choice(_FIRST_NAMES)} {random.choice(_LAST_NAMES)}"

    def _gen_first_name(self) -> str:
        return random.choice(_FIRST_NAMES)

    def _gen_last_name(self) -> str:
        return random.choice(_LAST_NAMES)

    def _gen_email(self) -> str:
        first = random.choice(_FIRST_NAMES).lower()
        last = random.choice(_LAST_NAMES).lower()
        suffix = "".join(random.choices(string.digits, k=3))
        domain = random.choice(_DOMAINS)
        return f"{first}.{last}{suffix}@{domain}"

    def _gen_random_int(self) -> int:
        lo = self.kwargs.get("min", 0)
        hi = self.kwargs.get("max", 100)
        return random.randint(lo, hi)

    def _gen_random_float(self) -> float:
        lo = self.kwargs.get("min", 0.0)
        hi = self.kwargs.get("max", 1.0)
        return round(random.uniform(lo, hi), 4)

    def _gen_text(self) -> str:
        max_length: int = self.kwargs.get("max_length", 200)
        words = random.choices(_WORDS, k=max_length // 5)
        return " ".join(words)[:max_length]

    def _gen_sentence(self) -> str:
        length = random.randint(5, 12)
        words = random.choices(_WORDS, k=length)
        return " ".join(words).capitalize() + "."

    def _gen_word(self) -> str:
        return random.choice(_WORDS)

    def _gen_uuid(self) -> str:
        return str(uuid.UUID(int=random.getrandbits(128), version=4))

    def _gen_boolean(self) -> bool:
        return random.choice([True, False])

    def _gen_date(self) -> date:
        days_back = random.randint(0, 365)
        return date.today() - timedelta(days=days_back)

    def _gen_datetime(self) -> datetime:
        seconds_back = random.randint(0, 365 * 24 * 3600)
        return datetime.now(tz=UTC) - timedelta(seconds=seconds_back)

    def _gen_choice(self) -> Any:
        return random.choice(self.kwargs["items"])

    def __repr__(self) -> str:
        if self.kwargs:
            kw = ", ".join(f"{k}={v!r}" for k, v in self.kwargs.items())
            return f"Faker({self.provider!r}, {kw})"
        return f"Faker({self.provider!r})"


