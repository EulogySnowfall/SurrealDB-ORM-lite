"""``ModelFactory`` and ``Faker``: Factory Boy-style test data, mirroring the full SurrealDB-ORM (v0.40.0).

The full ORM's ``surreal_orm.testing`` names, providers, pools and output formats, with no dependency: values come
from Python's ``random`` module, so ``random.seed(n)`` makes a test's data reproducible (``uuid`` included).

Example::

    from surreal_orm_lite.testing import Faker

    name = Faker("name")                                   # "Alice Smith"
    age = Faker("random_int", min=18, max=80)
    tag = Faker("choice", items=["tech", "science", "art"])
    age.generate()                                         # 42

Unlike the full ORM, a ``Faker`` checks its provider and keywords when it is built: an unknown provider, a keyword
the provider does not take or a ``choice`` without ``items`` fails at the declaration, not at the first value.

``random`` is not a cryptographic generator: these values (``uuid`` included) are **test data, never secrets or
tokens**. For an id generated by the server, declare ``SurrealFunc("rand::uuid::v7()")`` instead.
"""

