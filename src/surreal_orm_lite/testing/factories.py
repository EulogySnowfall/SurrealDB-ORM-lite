def _describe_callable(value: Any) -> str:
    """Name a refused callable attribute in its error: ``datetime.now``, ``functools.partial``, ``_Callable``."""
    qualname = getattr(value, "__qualname__", None)
    if isinstance(qualname, str):
        return qualname
    kind = type(value)
    return kind.__qualname__ if kind.__module__ == "builtins" else f"{kind.__module__}.{kind.__qualname__}"


def _collect_own(name: str, namespace: dict[str, Any]) -> dict[str, Any]:
    """Collect one class body's declarations, in declaration order, names as written.

    Ignored: a ``_`` name, ``Meta``, a function (lambdas included), a ``classmethod``/``staticmethod``/``property``
    and a class. Refused: any other callable (``datetime.now``, ``functools.partial(...)``, an instance with
    ``__call__``), which F1 may later give a lazy meaning. Collected: everything else.
    """
    own: dict[str, Any] = {}
    for key, value in namespace.items():
        if key.startswith("_") or key == "Meta":
            continue
        if inspect.isfunction(value) or isinstance(value, (classmethod, staticmethod, property, type)):
            continue
        if callable(value):
            raise TypeError(
                f"{name}.{key} is a callable ({_describe_callable(value)}); a factory attribute is a static value, "
                "a Faker or a SurrealFunc — lazy values are not supported yet"
            )
        own[key] = value
    return own


class _FactoryMeta(type):
    """Collect a factory's declarations and check them against its model when the ``class`` statement runs.

    ``ModelFactory[User]`` (a ``Generic`` alias) creates no class, so it runs nothing here: only a real ``class``
    statement does.
    """

    _own_defs: dict[str, Any]
    _field_defs: dict[str, Any]

    def __new__(mcs, name: str, bases: tuple[type, ...], namespace: dict[str, Any], **kwargs: Any) -> "_FactoryMeta":
        own = _collect_own(name, namespace)
        cls = super().__new__(mcs, name, bases, namespace, **kwargs)
        cls._own_defs = own
        model = cls._find_model()
        if model is None:
            merged: dict[str, Any] = {}
            for klass in reversed(cls.__mro__):
                merged.update(klass.__dict__.get("_own_defs", {}))
            cls._field_defs = merged
            return cls
        if not (isinstance(model, type) and issubclass(model, BaseSurrealModel)):
            raise TypeError(f"{name}.Meta.model must be a BaseSurrealModel subclass, not {model!r}")
        cls._field_defs = mcs._normalized_defs(name, cls, model)
        return cls

    def _find_model(cls) -> Any:
        """Return the ``model`` of the first class in the MRO whose own ``Meta`` sets one, else ``None`` (D12)."""
        for klass in cls.__mro__:
            meta = klass.__dict__.get("Meta")
            if meta is None:
                continue
            model = getattr(meta, "model", None)
            if model is not None:
                return model
        return None

    @staticmethod
    def _normalized_defs(name: str, cls: "_FactoryMeta", model: type[BaseSurrealModel]) -> dict[str, Any]:
        """Merge the MRO's declarations keyed by the model's Python field names, then check them (D14, D15)."""
        per_class: list[list[tuple[str, str, Any]]] = []
        for klass in reversed(cls.__mro__):
            own: dict[str, Any] = klass.__dict__.get("_own_defs", {})
            entries = [(raw, model.to_py_field(raw), value) for raw, value in own.items()]
            seen: dict[str, str] = {}
            for raw, py_name, _value in entries:
                if py_name in seen:
                    raise TypeError(
                        f"{name} declares {py_name!r} twice: as {py_name!r} and as its column {model.to_db_field(py_name)!r}"
                    )
                seen[py_name] = raw
            per_class.append(entries)
        if model.model_config.get("extra") != "allow":
            known = set(model.model_fields)
            for entries in per_class:
                for raw, py_name, _value in entries:
                    if py_name not in known:
                        fields = ", ".join(sorted(known))
                        raise TypeError(f"{name} declares {raw!r}, which is not a field of {model.__name__} (fields: {fields})")
        merged: dict[str, Any] = {}
        for entries in per_class:
            for _raw, py_name, value in entries:
                merged[py_name] = value
        if issubclass(model, BaseSurrealEdge):
            for py_name, value in merged.items():
                if isinstance(value, SurrealFunc):
                    raise TypeError(
                        f"{name} declares SurrealFunc {py_name!r}, but {model.__name__} is an edge: its save() "
                        "(INSERT RELATION) cannot evaluate server values. Use DEFINE FIELD … DEFAULT on the edge "
                        "table, or a plain value."
                    )
        return merged


class ModelFactory(Generic[M], metaclass=_FactoryMeta):
    """Factory Boy-style factory of model instances (the full SurrealDB-ORM's names and shape).

    Declare the model in ``Meta`` and its fields' test data as class attributes: a :class:`Faker` (a new value for
    each instance), a :class:`~surreal_orm_lite.SurrealFunc` (generated by the server on ``create()``, node models
    only) or any static value (deep-copied for each instance)::

        class UserFactory(ModelFactory[User]):     # or ModelFactory, as in the full ORM (build() is then typed
            class Meta:                            # BaseSurrealModel)
                model = User

            name = Faker("name")
            age = Faker("random_int", min=18, max=80)
            role = "player"

    A subclass inherits its parent's declarations (its own win) and its parent's model, also through a ``Meta`` that
    sets no ``model``. A factory without a model is an abstract base: definable, its declarations checked against the
    model of the subclass that sets one, and each of its methods raises ``ValueError``.

    Raises (at the ``class`` statement):
        TypeError: ``Meta.model`` is not a ``BaseSurrealModel`` subclass; an attribute is a callable other than a
            function, method or class; one class body declares a field under its Python name and its column; a
            declared name is no field of the model (unless the model has ``extra="allow"``); a ``SurrealFunc`` is
            declared on (or inherited by) an edge factory.
    """

    _field_defs: ClassVar[dict[str, Any]]

    class Meta:
        """Holds ``model``, the ``BaseSurrealModel`` subclass this factory builds."""

        model: type[BaseSurrealModel]

    @classmethod
    def _get_model(cls) -> type[BaseSurrealModel] | None:
        """Return the factory's model (the first ``Meta.model`` set along the MRO), or ``None`` on an abstract one."""
        model: type[BaseSurrealModel] | None = cls._find_model()
        return model

    @classmethod
    def _require_model(cls) -> type[BaseSurrealModel]:
        """Return the factory's model, or raise the full ORM's ``ValueError`` on an abstract factory."""
        model = cls._get_model()
        if model is None:
            raise ValueError(f"{cls.__name__}.Meta.model is not set. Define a Meta class with a model attribute.")
        return model

    @classmethod
    def build(cls, /, **overrides: Any) -> M:
        """Build one unsaved instance from the declarations and *overrides* (no database access)."""
        cls._require_model()
        raise NotImplementedError

    @classmethod
    def build_batch(cls, count: int, /, **overrides: Any) -> list[M]:
        """Build *count* unsaved instances, each with fresh ``Faker`` values and fresh copies."""
        cls._require_model()
        raise NotImplementedError

    @classmethod
    async def create(cls, /, **overrides: Any) -> M:
        """Build one instance and save it; the saved instance is returned."""
        cls._require_model()
        raise NotImplementedError

    @classmethod
    async def create_batch(cls, count: int, /, **overrides: Any) -> list[M]:
        """Create *count* instances one by one (one ``save()`` each)."""
        cls._require_model()
        raise NotImplementedError
